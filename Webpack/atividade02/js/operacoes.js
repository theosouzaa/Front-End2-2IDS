export function somar(numero1, numero2) {
    console.log('Função somar calculadora.js')
    return numero1 + numero2;
}

export function subtracao(numero1, numero2) {
    console.log('Função subtração calculadora.js')
    return numero1 - numero2;
}

export function multiplicar(numero1, numero2) {
    console.log('Função multiplicar calculadora.js')
    return numero1 * numero2;
}

export function dividir(numero1, numero2) {
    console.log('Função dividir calculadora.js')
    return numero1 / numero2;
}